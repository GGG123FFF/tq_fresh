/**
 * Elemental sprites, three growth stages.
 *
 * Pixel art generated from source rather than drawn into sheets. Each frame is
 * a grid of characters, one per pixel, so the whole cast is a few kilobytes of
 * readable text that diffs properly in git — no binary assets, no atlas.
 *
 *   Stage 0  a small flame-spirit. Shared body, element crown and palette.
 *            Calcifer-sized: all face, barely any silhouette.
 *   Stage 1  an adolescent elemental. Shared body, now with arms and some
 *            presence, still recognisably the same creature grown up.
 *   Stage 2  a distinct form per colour. Nothing shared but the palette and
 *            the face — a white angel and a green treefolk should not read as
 *            the same animal wearing a different hat.
 *
 * One 32x32 grid for every stage, with stage 0 occupying a small patch of it.
 * Growth is then literally growth: the creature fills more of the same frame
 * rather than the frame changing size.
 *
 * The grid is 16 wide by 32 tall. Creatures are taller than they are wide, so
 * a square frame would waste half of itself on empty columns.
 *
 * An earlier version authored 16 columns and mirrored them to 32 for free
 * symmetry. That was wrong: these blocks are whole centred creatures, not left
 * halves, so mirroring produced two of everything facing each other. Symmetry
 * here is just a property of how they're drawn.
 *
 * Legend
 *   .  transparent   1..4  palette ramp, dark to bright
 *   o  outline       w  eye white   p  pupil   m  mouth
 */

