/** Hover cycle: the body, then the body one pixel lower, alternating. */
function frames(base) {
  const a = base;
  const b = '\n' + base.replace(/^\n/, '').split('\n').slice(0, H - 1).join('\n');
  return [a, b, a, b];
}

