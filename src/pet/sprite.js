export const STAGE_NAMES = ['Spark', 'Elemental', 'Ascendant'];

// --------------------------------------------------------------------------
// Compositing
// --------------------------------------------------------------------------
function rows(block) {
  const raw = block.replace(/^\n/, '').split('\n');
  const out = [];
  for (let y = 0; y < H; y++) out.push((raw[y] || '').padEnd(W, '.').slice(0, W));
  return out;
}

function stamp(grid, run, row, dx = 0) {
  if (row < 0 || row >= H) return;
  const start = Math.floor((W - run.length) / 2) + dx;
  if (run.length > W) return;
  const line = grid[row].split('');
  for (let i = 0; i < run.length; i++) {
    const x = start + i;
    if (x < 0 || x >= W) continue;
    if (run[i] !== '.') line[x] = run[i];
  }
  grid[row] = line.join('');
}

const STAGE0 = frames(S0);
const STAGE1 = frames(S1);

/** Build one frame's grid. `stage` 0-2, `element` one of WUBRG. */
export function buildFrame(element, stage = 0, frame = 0, face = 'open') {
  const el = PALETTES[element] ? element : 'R';
  const st = Math.max(0, Math.min(2, stage));
  const block = st === 2 ? frames(STAGE2[el])[frame % 4]
    : st === 1 ? STAGE1[frame % 4]
      : STAGE0[frame % 4];

  const grid = rows(block);
  const drop = frame % 2;
  const anchor = (st === 2 ? ANCHOR2[el] : ANCHOR[st]) + drop;

  if (st < 2) {
    for (const [run, r] of CROWNS[el]) stamp(grid, run, anchor - 6 + r);
  }
  for (const [run, r] of FACES[face] || FACES.open) stamp(grid, run, anchor + r);
  return grid;
}

/** Draw to a 2D context at `scale` pixels per cell. */
export function drawFrame(ctx, element, stage, frame, face, scale = 5, glow = true) {
  const pal = PALETTES[element] || PALETTES.R;
  const grid = buildFrame(element, stage, frame, face);

  if (glow) {
    const cx = (W / 2) * scale;
    const cy = (H / 2) * scale;
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, H * scale * 0.42);
    g.addColorStop(0, pal.g);
    g.addColorStop(1, 'rgba(0,0,0,0)');
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W * scale, H * scale);
  }

  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const ch = grid[y][x];
      if (ch === '.') continue;
      const colour = pal[ch];
      if (!colour) continue;
      ctx.fillStyle = colour;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
}

